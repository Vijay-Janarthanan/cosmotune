package com.cosmotune.music.data.lyrics

import com.cosmotune.music.data.Http
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.longOrNull
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonObject
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import java.util.concurrent.TimeUnit

/**
 * The playing video's own caption track, as the lyrics of last resort.
 *
 * Ported from Mochy Music (https://github.com/realidkroo/Mochy-Music, GPL-3.0), whose
 * `YouTubeCaptionsLyricsProvider` and `providers/innertube/Captions.kt` choose the track and read it the same way: the
 * auto-generated track names the language that is sung, an uploaded track in that language wins over it (an uploaded track
 * in another language is as often a translation as not), and with no auto-generated track nothing is picked.
 *
 * Speech recognition hears sung words wrong often enough that this is asked only when every other source has missed: it is
 * declared last in [LyricsSource] and started lazily by [LyricsRepository]. An uploaded track is timed by the line. An
 * auto-generated one times each word YouTube heard, and those times are kept as word timing.
 *
 * Unlike [YouTubeTranscriptLyrics] (the `get_transcript` panel, which many music videos do not offer), this reads the
 * timed-text file the player itself downloads, through a client whose caption links need no proof-of-origin token.
 */
object YouTubeCaptionLyrics {

    /** One of the player's caption tracks. [autoGenerated] is YouTube's `kind == "asr"`. */
    data class Track(val baseUrl: String, val languageCode: String, val autoGenerated: Boolean)

    suspend fun lyrics(videoId: String): List<LyricLine>? = withContext(Dispatchers.IO) {
        if (!VIDEO_ID.matches(videoId)) return@withContext null
        val player = runCatching { player(videoId) }.getOrNull() ?: return@withContext null
        val track = pickTrack(tracksOf(player)) ?: return@withContext null
        val body = runCatching { get(withJson3(track.baseUrl)) }.getOrNull() ?: return@withContext null
        parseTimedText(body, wordTimed = track.autoGenerated).takeIf { it.size >= MIN_LINES }
    }

    /** The auto-generated track, or an uploaded one in its language; null when there is no auto-generated track. */
    fun pickTrack(tracks: List<Track>): Track? {
        val auto = tracks.firstOrNull { it.autoGenerated } ?: return null
        val language = auto.languageCode.substringBefore('-')
        return tracks.firstOrNull { !it.autoGenerated && it.languageCode.substringBefore('-') == language } ?: auto
    }

    fun tracksOf(player: JsonElement): List<Track> {
        val list = ((player as? JsonObject)?.get("captions") as? JsonObject)
            ?.get("playerCaptionsTracklistRenderer")?.let { it as? JsonObject }
            ?.get("captionTracks") as? JsonArray ?: return emptyList()
        return list.mapNotNull { element ->
            val track = element as? JsonObject ?: return@mapNotNull null
            val url = track.string("baseUrl") ?: return@mapNotNull null
            Track(url, track.string("languageCode").orEmpty(), track.string("kind") == "asr")
        }
    }

    /**
     * Timed-text JSON (`fmt=json3`) as lyric lines: one line per caption event, the empty line-break events and sound labels
     * such as "[Music]" left out, and a rolling caption's repeat of the line before it dropped. With [wordTimed], each segment
     * that carries its own offset becomes a word ending where the next begins (or where the event ends).
     */
    fun parseTimedText(json: String, wordTimed: Boolean): List<LyricLine> {
        val root = runCatching { lyricsJson.parseToJsonElement(json) }.getOrNull() as? JsonObject ?: return emptyList()
        val events = root["events"] as? JsonArray ?: return emptyList()
        val parsed = events.mapNotNull { element ->
            val event = element as? JsonObject ?: return@mapNotNull null
            val start = event.long("tStartMs") ?: return@mapNotNull null
            val segs = event["segs"] as? JsonArray ?: return@mapNotNull null
            val end = start + (event.long("dDurationMs") ?: 0L)
            // Each piece as (start, text); a segment without its own offset belongs to the piece before it.
            val pieces = ArrayList<Pair<Long, StringBuilder>>()
            for (seg in segs) {
                val segment = seg as? JsonObject ?: continue
                val text = segment.string("utf8").orEmpty()
                val offset = segment.long("tOffsetMs")
                if (offset != null || pieces.isEmpty()) pieces += (start + (offset ?: 0L)) to StringBuilder(text)
                else pieces.last().second.append(text)
            }
            val words = pieces.mapIndexedNotNull { index, (pieceStart, raw) ->
                val text = clean(raw.toString())
                if (text.isEmpty()) return@mapIndexedNotNull null
                val pieceEnd = pieces.getOrNull(index + 1)?.first ?: end
                LyricWord(pieceStart, maxOf(pieceEnd, pieceStart + 1), text)
            }
            if (words.isEmpty()) return@mapNotNull null
            Triple(start, end, words)
        }.sortedBy { it.first }

        val lines = ArrayList<LyricLine>()
        var previous: String? = null
        parsed.forEachIndexed { index, (start, end, words) ->
            val text = words.joinToString(" ") { it.text }
            if (text == previous) return@forEachIndexed
            previous = text
            // A word cannot outlast the next caption: the auto track's windows overlap while they scroll.
            val nextStart = parsed.getOrNull(index + 1)?.first
            val clipped = if (nextStart == null) words else words.map { word ->
                if (word.endMs > nextStart && word.startMs < nextStart) word.copy(endMs = nextStart) else word
            }
            val timedWords = if (wordTimed && clipped.size > 1) clipped else emptyList()
            lines += LyricLine(
                timeMs = start,
                text = text,
                words = timedWords,
                sungUntilMs = (nextStart?.let { minOf(it, end) } ?: end).takeIf { it > start },
            )
        }
        return lines
    }

    private fun clean(text: String): String =
        text.replace(SOUND_LABEL, " ").replace('♪', ' ').replace(WHITESPACE, " ").trim()

    private fun withJson3(url: String): String {
        val stripped = url.replace(FMT_PARAM, "")
        return stripped + (if ('?' in stripped) "&" else "?") + "fmt=json3"
    }

    private fun player(videoId: String): JsonElement? {
        val body = buildJsonObject {
            putJsonObject("context") {
                putJsonObject("client") {
                    put("clientName", "ANDROID_VR")
                    put("clientVersion", VR_VERSION)
                    put("deviceMake", "Oculus")
                    put("deviceModel", "Quest 3")
                    put("androidSdkVersion", 32)
                    put("osName", "Android")
                    put("osVersion", "12L")
                    put("hl", "en")
                    put("gl", "US")
                }
            }
            put("videoId", videoId)
            put("contentCheckOk", true)
            put("racyCheckOk", true)
        }.toString()
        val request = Request.Builder()
            .url("https://www.youtube.com/youtubei/v1/player?prettyPrint=false")
            .header("User-Agent", VR_AGENT)
            .header("X-YouTube-Client-Name", "28")
            .header("X-YouTube-Client-Version", VR_VERSION)
            .post(body.toRequestBody("application/json".toMediaType()))
            .build()
        return client.newCall(request).execute().use { response ->
            if (!response.isSuccessful) null else response.body?.string()?.let(lyricsJson::parseToJsonElement)
        }
    }

    private fun get(url: String): String? {
        val request = Request.Builder().url(url).header("User-Agent", VR_AGENT).build()
        return client.newCall(request).execute().use { response ->
            if (response.isSuccessful) response.body?.string() else null
        }
    }

    private val client by lazy {
        Http.client.newBuilder().callTimeout(8, TimeUnit.SECONDS).connectTimeout(3, TimeUnit.SECONDS).build()
    }

    private fun JsonObject.string(key: String): String? = (this[key] as? JsonPrimitive)?.contentOrNull
    private fun JsonObject.long(key: String): Long? = (this[key] as? JsonPrimitive)?.longOrNull

    /** Fewer lines than this is a jingle or a spoken intro, not a song's words. */
    private const val MIN_LINES = 3
    private const val VR_VERSION = "1.65.10"
    private const val VR_AGENT = "com.google.android.apps.youtube.vr.oculus/1.65.10 " +
        "(Linux; U; Android 12L; eureka-user Build/SQ3A.220605.009.A1) gzip"
    private val VIDEO_ID = Regex("""[A-Za-z0-9_-]{11}""")
    private val SOUND_LABEL = Regex("""\[[^\]]*\]""")
    private val WHITESPACE = Regex("""\s+""")
    private val FMT_PARAM = Regex("""[&?]fmt=[^&]*""")
}
