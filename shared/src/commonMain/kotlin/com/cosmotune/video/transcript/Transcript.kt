package com.cosmotune.video.transcript

import com.cosmotune.video.model.SubtitleTrack

/** One line of a video's transcript: when it is said and what. */
data class TranscriptLine(val startMs: Long, val text: String)

/**
 * The watch page's Transcript: a caption track read as lines that seek when tapped. The machine-made tracks repeat each line as the
 * next one rolls in; those repeats are folded away, so each words show once.
 */
object Transcript {
    private val TIMING = Regex("""^\s*((?:\d+:)?\d{1,2}:\d{2}[.,]\d{1,3})\s+-->\s+""")
    private val TAG = Regex("""<[^>]*>""")

    fun parse(vtt: String): List<TranscriptLine> {
        val lines = vtt.replace("\r\n", "\n").split('\n')
        val out = ArrayList<TranscriptLine>()
        var i = 0
        while (i < lines.size) {
            val m = TIMING.find(lines[i])
            if (m == null) { i++; continue }
            val start = timeMs(m.groupValues[1])
            i++
            val text = StringBuilder()
            while (i < lines.size && lines[i].isNotBlank()) {
                val clean = decode(TAG.replace(lines[i], "")).trim()
                if (clean.isNotEmpty()) {
                    if (text.isNotEmpty()) text.append(' ')
                    text.append(clean)
                }
                i++
            }
            if (start != null && text.isNotBlank()) out += TranscriptLine(start, text.toString())
        }
        return fold(out)
    }

    /** Drops repeats: a line equal to the last, and the start of a line that repeats the end of the one before (rolling captions). */
    private fun fold(lines: List<TranscriptLine>): List<TranscriptLine> {
        val out = ArrayList<TranscriptLine>()
        for (line in lines) {
            val last = out.lastOrNull()
            if (last == null) { out += line; continue }
            if (line.text == last.text) continue
            val rest = if (line.text.startsWith(last.text)) line.text.removePrefix(last.text).trim() else line.text
            if (rest.isNotEmpty()) out += TranscriptLine(line.startMs, rest)
        }
        return out
    }

    /** The index of the line playing at [positionMs], or -1 before the first. */
    fun indexAt(lines: List<TranscriptLine>, positionMs: Long): Int = lines.indexOfLast { it.startMs <= positionMs }

    /** The track the transcript reads: [preferred] language, else one made by a person, else the first. */
    fun pick(tracks: List<SubtitleTrack>, preferred: String?): SubtitleTrack? {
        fun same(a: String, b: String) = a.substringBefore('-').equals(b.substringBefore('-'), ignoreCase = true)
        return preferred?.let { p -> tracks.firstOrNull { same(it.language, p) && !it.autoGenerated } ?: tracks.firstOrNull { same(it.language, p) } }
            ?: tracks.firstOrNull { !it.autoGenerated }
            ?: tracks.firstOrNull()
    }

    private fun timeMs(text: String): Long? {
        val parts = text.replace(',', '.').split(':')
        val seconds = parts.last().toDoubleOrNull() ?: return null
        val minutes = parts.getOrNull(parts.size - 2)?.toLongOrNull() ?: 0
        val hours = if (parts.size == 3) parts[0].toLongOrNull() ?: 0 else 0
        return ((hours * 3600 + minutes * 60) * 1000) + (seconds * 1000).toLong()
    }

    private fun decode(text: String): String = text.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
        .replace("&quot;", "\"").replace("&#39;", "'").replace("&nbsp;", " ")
}
