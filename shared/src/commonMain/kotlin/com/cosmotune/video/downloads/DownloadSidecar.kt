package com.cosmotune.video.downloads

import com.cosmotune.video.model.AudioCodec
import com.cosmotune.video.model.Chapter
import com.cosmotune.video.model.VideoCodec
import com.cosmotune.video.model.VideoItem
import com.cosmotune.video.segments.SegmentAction
import com.cosmotune.video.segments.SegmentCategory
import com.cosmotune.video.segments.SkipSegment
import kotlinx.serialization.Serializable

/** One subtitle file beside a download: its file name, language tag, label and whether a machine made it. */
data class SidecarSubtitle(val file: String, val language: String, val label: String, val autoGenerated: Boolean)

/**
 * The small file beside each download, `<name>.cosmotune.json` (spec 5.10; plan task Y-24, step 5): the item, its chapters,
 * the SponsorBlock segments fetched at download time (empty when offline), the subtitle files, the quality, the container and
 * codecs, the subtitle language it got (null for none), the media file names (one, or the pair when the join failed) and
 * when it was downloaded. File names are relative to the folder, so the folder can be moved. A version field like every file
 * of the mode (spec 8.1).
 */
data class DownloadSidecar(
    val item: VideoItem,
    val chapters: List<Chapter>,
    val segments: List<SkipSegment>,
    val subtitles: List<SidecarSubtitle>,
    val quality: String,
    val container: DownloadContainer,
    val videoCodec: VideoCodec?,
    val audioCodec: AudioCodec,
    val languageGot: String?,
    val files: List<String>,
    val downloadedAtMs: Long,
) {
    companion object {
        /** The format's version. */
        const val VERSION = 1

        /** What the sidecar's name adds to the download's base name. */
        const val SUFFIX = ".cosmotune.json"

        /** The sidecar of the download named [baseName]: "<name>.cosmotune.json". */
        fun fileName(baseName: String): String = "$baseName$SUFFIX"

        /** [sidecar] as JSON (segments by their SponsorBlock names, enums by name). */
        fun encode(sidecar: DownloadSidecar): String = DownloadsFile.json.encodeToString(SidecarDto.serializer(), SidecarDto(
            version = VERSION,
            item = sidecar.item.toDto(),
            chapters = sidecar.chapters.map { ChapterDto(it.title, it.startMs, it.thumbnailUrl) },
            segments = sidecar.segments.map {
                SegmentDto(it.uuid, it.category.apiName, it.action.name, it.startMs, it.endMs, it.videoDurationMs, it.votes, it.locked, it.description)
            },
            subtitles = sidecar.subtitles.map { SidecarSubtitleDto(it.file, it.language, it.label, it.autoGenerated) },
            quality = sidecar.quality,
            container = sidecar.container.name,
            videoCodec = sidecar.videoCodec?.name,
            audioCodec = sidecar.audioCodec.name,
            languageGot = sidecar.languageGot,
            files = sidecar.files,
            downloadedAtMs = sidecar.downloadedAtMs,
        ))

        /** The sidecar in [text], or null when it is not one; unknown fields are ignored and unknown segment categories dropped. */
        fun decode(text: String): DownloadSidecar? {
            val dto = runCatching { DownloadsFile.json.decodeFromString(SidecarDto.serializer(), text) }.getOrNull() ?: return null
            return runCatching {
                DownloadSidecar(
                    item = dto.item.toItem(),
                    chapters = dto.chapters.map { Chapter(it.title, it.startMs, it.thumbnailUrl) },
                    segments = dto.segments.mapNotNull { s ->
                        val category = SegmentCategory.of(s.category) ?: return@mapNotNull null
                        val action = DownloadsFile.enumOrNull<SegmentAction>(s.action) ?: return@mapNotNull null
                        SkipSegment(s.uuid, category, action, s.startMs, s.endMs, s.videoDurationMs, s.votes, s.locked, s.description)
                    },
                    subtitles = dto.subtitles.map { SidecarSubtitle(it.file, it.language, it.label, it.autoGenerated) },
                    quality = dto.quality,
                    container = DownloadsFile.enumOrNull<DownloadContainer>(dto.container) ?: DownloadContainer.MP4,
                    videoCodec = DownloadsFile.enumOrNull<VideoCodec>(dto.videoCodec),
                    audioCodec = DownloadsFile.enumOrNull<AudioCodec>(dto.audioCodec) ?: AudioCodec.OTHER,
                    languageGot = dto.languageGot,
                    files = dto.files,
                    downloadedAtMs = dto.downloadedAtMs,
                )
            }.getOrNull()
        }
    }
}

@Serializable
internal data class SidecarDto(
    val version: Int,
    val item: ItemDto,
    val chapters: List<ChapterDto> = emptyList(),
    val segments: List<SegmentDto> = emptyList(),
    val subtitles: List<SidecarSubtitleDto> = emptyList(),
    val quality: String,
    val container: String,
    val videoCodec: String? = null,
    val audioCodec: String,
    val languageGot: String? = null,
    val files: List<String> = emptyList(),
    val downloadedAtMs: Long = 0,
)

@Serializable
internal data class ChapterDto(val title: String, val startMs: Long, val thumbnailUrl: String? = null)

@Serializable
internal data class SegmentDto(
    val uuid: String, val category: String, val action: String, val startMs: Long, val endMs: Long, val videoDurationMs: Long? = null,
    val votes: Int = 0, val locked: Boolean = false, val description: String? = null,
)

@Serializable
internal data class SidecarSubtitleDto(val file: String, val language: String, val label: String, val autoGenerated: Boolean = false)
