package com.cosmotune.video.downloads

import com.cosmotune.video.player.LocalBundle
import com.cosmotune.video.player.LocalSubtitle

/**
 * The sidecar of a finished download (spec 5.10): "<folder>/<name>.cosmotune.json" beside its file, where <name> is the file's
 * name without its extension (without ".video.<ext>" for a pair kept after a failed join); null until the entry is done.
 */
fun DownloadEntry.sidecarPath(): String? {
    val done = state as? DownloadState.Done ?: return null
    val cut = lastSeparator(done.path) + 1
    val name = done.path.substring(cut)
    val pair = localFiles()?.videoPath != null
    val base = if (pair) name.removeSuffix(".video.${DownloadPlanner.videoExtension(choice.video)}") else name.substringBeforeLast('.')
    return done.path.substring(0, cut) + DownloadSidecar.fileName(base)
}

/**
 * What the player needs to watch a finished download offline (the owner's decision: with its subtitles, chapters and the
 * SponsorBlock segments cached at download time): the file or the pair ([localFiles]), and from [sidecarJson] (the text of
 * [sidecarPath]) the subtitle files with their language and label, the chapters and the segments. A missing or unreadable
 * sidecar, or one of another video, gives the files alone, with the subtitle files the entry itself records (their language
 * read from the name "<name>.<tag>.vtt", their label the entry's [DownloadEntry.subtitleGot]); no chapters, no segments.
 * Null until the entry is done. Pure: the caller reads the file (`readLocalBundle` on both platforms) and hands the bundle to
 * `VideoPlayback.playLocal(item, bundle, startMs)`. The sidecar keeps no description: the offline watch page hides an empty one.
 */
fun DownloadEntry.toLocalBundle(sidecarJson: String?): LocalBundle? {
    val files = localFiles() ?: return null
    val done = state as DownloadState.Done
    val folder = done.path.substring(0, lastSeparator(done.path) + 1)
    val sidecar = sidecarJson?.let { DownloadSidecar.decode(it) }?.takeIf { it.item.id == item.id }
        ?: return LocalBundle(files, subtitleFiles.map { path -> fromEntry(path) }, emptyList(), emptyList())
    return LocalBundle(
        files = files,
        subtitles = sidecar.subtitles.map { LocalSubtitle(folder + it.file, it.language, it.label, it.autoGenerated) },
        chapters = sidecar.chapters.sortedBy { it.startMs },
        segments = sidecar.segments,
    )
}

/** A subtitle file the entry records, without its sidecar: "<name>.<tag>.vtt" gives the tag; the label is the one the entry got. */
private fun DownloadEntry.fromEntry(path: String): LocalSubtitle {
    val tag = path.substring(lastSeparator(path) + 1).removeSuffix(".vtt").substringAfterLast('.', "")
    val label = subtitleGot ?: tag
    return LocalSubtitle(path, tag, label, autoGenerated = label.endsWith("(auto-generated)"))
}

private fun lastSeparator(path: String) = maxOf(path.lastIndexOf('/'), path.lastIndexOf('\\'))
