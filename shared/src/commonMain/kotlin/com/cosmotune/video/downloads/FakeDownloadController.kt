package com.cosmotune.video.downloads

import com.cosmotune.video.model.AudioCodec
import com.cosmotune.video.model.VideoCodec
import com.cosmotune.video.model.VideoItem
import com.cosmotune.video.player.QualityOption
import com.cosmotune.video.source.FakeVideoSource
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlin.jvm.Synchronized
import kotlin.math.min

/**
 * The download engine in memory (plan task Y-2, step 3), for the sheet and the Downloads page: the queue runs one item at
 * a time, first in first out, and [advance] moves it along one step (start the next waiting item, add [STEP] to the running
 * one, join, finish); [runUntilIdle] advances until nothing is left to do; [fail] makes an entry fail. [options] offers the
 * ladder 2160p60 to 144p with sizes, a subtitle list of English, Hindi and an auto-generated English; [batchOptions] the
 * batch form ("about" sizes; the app's language and each video's original language). Nothing touches a file.
 */
class FakeDownloadController(
    private val clock: () -> Long = { FakeVideoSource.NOW_MS },
    private val freeBytes: Long = 21L * 1024 * 1024 * 1024,
) : DownloadController {
    private val entries = MutableStateFlow<List<DownloadEntry>>(emptyList())
    private val batchFlow = MutableStateFlow<List<BatchState>>(emptyList())
    private val batchInfos = mutableListOf<DownloadBatchInfo>()
    private val pausedBatches = mutableSetOf<String>()
    private val progress = mutableMapOf<String, Float>()
    private var counter = 0

    override val downloads: StateFlow<List<DownloadEntry>> = entries.asStateFlow()
    override val batches: StateFlow<List<BatchState>> = batchFlow.asStateFlow()

    override suspend fun options(item: VideoItem): DownloadOptions {
        val seconds = item.durationSec ?: DEFAULT_SECONDS
        return DownloadOptions(
            autoMeans = QualityOption.labelOf(LADDER.first().first, LADDER.first().second, hdr = false),
            rungs = LADDER.map { (h, fps) -> rung(h, fps, bytesOf(kbpsOf(h), seconds), estimate = false) },
            audioOnly = RungOption(DownloadQuality.AudioOnly, AUDIO_ONLY_LABEL, "AAC", bytesOf(AUDIO_KBPS, seconds), isEstimate = false),
            subtitleLanguages = listOf(
                SubtitleLanguage("en", "English", autoGenerated = false),
                SubtitleLanguage("hi", "Hindi", autoGenerated = false),
                SubtitleLanguage("en", "English", autoGenerated = true),
            ),
            originalLanguage = "en",
        )
    }

    override suspend fun batchOptions(items: List<VideoItem>): DownloadOptions {
        val seconds = items.sumOf { it.durationSec ?: DEFAULT_SECONDS }
        return DownloadOptions(
            autoMeans = QualityOption.labelOf(LADDER.first().first, LADDER.first().second, hdr = false),
            rungs = LADDER.map { (h, fps) -> rung(h, fps, bytesOf(kbpsOf(h), seconds), estimate = true) },
            audioOnly = RungOption(DownloadQuality.AudioOnly, AUDIO_ONLY_LABEL, "AAC", bytesOf(AUDIO_KBPS, seconds), isEstimate = true),
            subtitleLanguages = listOf(
                SubtitleLanguage("en", "English", autoGenerated = false),
                SubtitleLanguage("", "Each video's original language", autoGenerated = false),
            ),
            originalLanguage = null,
        )
    }

    @Synchronized
    override fun enqueue(item: VideoItem, request: DownloadRequest) {
        if (has(item.id)) return
        entries.value = entries.value + newEntry(item, request, batch = null)
    }

    @Synchronized
    override fun enqueueBatch(info: DownloadBatchInfo, items: List<VideoItem>, request: DownloadRequest) {
        val fresh = items.distinctBy { it.id }.filterNot { has(it.id) }
        if (fresh.isEmpty()) return
        batchInfos.removeAll { it.id == info.id }
        batchInfos += info
        entries.value = entries.value + fresh.map { newEntry(it, request, info) }
        refreshBatches()
    }

    @Synchronized
    override fun pause(id: String) = edit(id) { e ->
        when (val s = e.state) {
            is DownloadState.Running -> {
                progress[e.id] = s.fraction
                e.copy(state = DownloadState.Paused(PauseReason.USER))
            }
            DownloadState.Waiting, DownloadState.WaitingForWifi -> e.copy(state = DownloadState.Paused(PauseReason.USER))
            else -> e
        }
    }

    @Synchronized
    override fun resume(id: String) = edit(id) { e -> if (e.state is DownloadState.Paused) e.copy(state = DownloadState.Waiting) else e }

    @Synchronized
    override fun pauseBatch(batchId: String) {
        pausedBatches += batchId
        entries.value.filter { it.batch?.id == batchId }.forEach { pause(it.id) }
        refreshBatches()
    }

    @Synchronized
    override fun resumeBatch(batchId: String) {
        pausedBatches -= batchId
        entries.value.filter { it.batch?.id == batchId && it.state == DownloadState.Paused(PauseReason.USER) }.forEach { resume(it.id) }
        refreshBatches()
    }

    @Synchronized
    override fun cancel(id: String) = removeEntry(id)

    @Synchronized
    override fun cancelBatch(batchId: String) {
        entries.value.filter { it.batch?.id == batchId }.forEach { progress -= it.id }
        entries.value = entries.value.filterNot { it.batch?.id == batchId }
        batchInfos.removeAll { it.id == batchId }
        pausedBatches -= batchId
        refreshBatches()
    }

    @Synchronized
    override fun remove(id: String) = removeEntry(id)

    @Synchronized
    override fun retry(id: String) = edit(id) { e -> if (e.state is DownloadState.Failed) e.copy(state = DownloadState.Waiting) else e }

    override fun storage(): Pair<Long, Long> =
        entries.value.sumOf { (it.state as? DownloadState.Done)?.bytes ?: 0L } to freeBytes

    /**
     * One step of the queue: the running or joining entry moves on (running by [STEP] up to 1, then joining, or done for
     * audio only; joining becomes done with its file); with none, the first waiting entry whose batch is not paused starts.
     */
    @Synchronized
    fun advance() {
        val list = entries.value
        val active = list.firstOrNull { it.state is DownloadState.Running || it.state == DownloadState.Joining }
        if (active == null) {
            val next = list.firstOrNull { it.state == DownloadState.Waiting && !it.batchPaused() } ?: return
            edit(next.id) { it.copy(state = DownloadState.Running(progress[it.id] ?: 0f)) }
            return
        }
        edit(active.id) { e ->
            when (val s = e.state) {
                is DownloadState.Running ->
                    if (s.fraction < 1f) e.copy(state = DownloadState.Running(min(1f, s.fraction + STEP)))
                    else if (e.kind == DownloadKind.AUDIO) finished(e)
                    else e.copy(state = DownloadState.Joining)
                DownloadState.Joining -> finished(e)
                else -> e
            }
        }
    }

    /** Advances until no entry is waiting, running or joining (paused and failed entries stay). */
    @Synchronized
    fun runUntilIdle() {
        var guard = 0
        while (guard++ < 10_000 && entries.value.any { it.state is DownloadState.Running || it.state == DownloadState.Joining ||
                (it.state == DownloadState.Waiting && !it.batchPaused()) }) {
            advance()
        }
    }

    /** Makes entry [id] fail with [reason]. */
    @Synchronized
    fun fail(id: String, reason: String = "Network error") = edit(id) { it.copy(state = DownloadState.Failed(reason)) }

    private fun DownloadEntry.batchPaused(): Boolean = batch != null && batch.id in pausedBatches

    private fun has(videoId: String) = entries.value.any { it.item.id == videoId && it.state !is DownloadState.Failed }

    private fun newEntry(item: VideoItem, request: DownloadRequest, batch: DownloadBatchInfo?): DownloadEntry {
        counter += 1
        val kind = when {
            request.quality == DownloadQuality.AudioOnly -> DownloadKind.AUDIO
            item.isShort -> DownloadKind.SHORT
            else -> DownloadKind.VIDEO
        }
        return DownloadEntry(
            id = "download-$counter", item = item, kind = kind, choice = choiceFor(item, request.quality), request = request,
            state = DownloadState.Waiting, batch = batch, subtitleFiles = emptyList(), subtitleGot = null, createdMs = clock(),
        )
    }

    private fun choiceFor(item: VideoItem, quality: DownloadQuality): DownloadChoice {
        val streams = FakeVideoSource.streamSetFor(item, clock())
        val seconds = item.durationSec ?: DEFAULT_SECONDS
        val aac = streams.audio.firstOrNull { it.codec == AudioCodec.AAC } ?: streams.audio.first()
        if (quality == DownloadQuality.AudioOnly) {
            return DownloadChoice(null, aac, DownloadContainer.M4A, bytesOf(AUDIO_KBPS, seconds), AUDIO_ONLY_LABEL)
        }
        val wanted = when (quality) {
            is DownloadQuality.Rung -> quality.height
            else -> LADDER.first().first
        }
        val candidates = streams.videoOnly.filter { it.height <= wanted }.ifEmpty { streams.videoOnly }
        val bestHeight = candidates.maxOf { it.height }
        val video = candidates.filter { it.height == bestHeight }.let { same -> same.firstOrNull { it.codec == VideoCodec.H264 } ?: same.first() }
        val opus = streams.audio.firstOrNull { it.codec == AudioCodec.OPUS } ?: aac
        val webm = video.codec == VideoCodec.VP9
        val bytes = bytesOf(kbpsOf(video.height), seconds)
        return DownloadChoice(
            video = video, audio = if (webm) opus else aac, container = if (webm) DownloadContainer.WEBM else DownloadContainer.MP4,
            estimatedBytes = bytes, label = QualityOption.labelOf(video.height, video.fps, video.hdr),
        )
    }

    private fun finished(e: DownloadEntry): DownloadEntry {
        progress -= e.id
        val extension = e.choice.container.name.lowercase()
        val name = "/fake/Movies/Cosmotune/${e.item.title.take(40)} [${e.item.id}]"
        val pick = e.request.subtitles
        val tag = if (pick.enabled) pick.language ?: "en" else null
        return e.copy(
            state = DownloadState.Done("$name.$extension", e.choice.estimatedBytes),
            subtitleFiles = if (tag != null) listOf("$name.$tag.vtt") else emptyList(),
            subtitleGot = tag?.let { LANGUAGE_NAMES[it] ?: it },
        )
    }

    private fun edit(id: String, change: (DownloadEntry) -> DownloadEntry) {
        entries.value = entries.value.map { if (it.id == id) change(it) else it }
        refreshBatches()
    }

    private fun removeEntry(id: String) {
        progress -= id
        entries.value = entries.value.filterNot { it.id == id }
        refreshBatches()
    }

    private fun refreshBatches() {
        val list = entries.value
        batchInfos.removeAll { info -> list.none { it.batch?.id == info.id } }
        batchFlow.value = batchInfos.map { info ->
            val items = list.filter { it.batch?.id == info.id }
            BatchState(info, total = items.size, done = items.count { it.state is DownloadState.Done }, paused = info.id in pausedBatches)
        }
    }

    private fun rung(height: Int, fps: Int, bytes: Long, estimate: Boolean) = RungOption(
        quality = DownloadQuality.Rung(height, fps), label = QualityOption.labelOf(height, fps, hdr = false),
        codec = if (height >= 1440) "VP9" else "H.264", estimatedBytes = bytes, isEstimate = estimate,
    )

    companion object {
        /** How far one [advance] moves a running download. */
        const val STEP = 0.25f

        /** The ladder [options] offers, as height and frame rate. */
        val LADDER: List<Pair<Int, Int>> = listOf(2160 to 60, 1440 to 60, 1080 to 60, 720 to 60, 480 to 30, 360 to 30, 240 to 30, 144 to 30)

        private const val AUDIO_ONLY_LABEL = "Audio only"
        private const val AUDIO_KBPS = 128
        private const val DEFAULT_SECONDS = 600L
        private val LANGUAGE_NAMES = mapOf("en" to "English", "hi" to "Hindi")

        /** Typical total bitrates with audio (plan task Y-24's table), kbit/s. */
        private fun kbpsOf(height: Int): Int = when {
            height >= 2160 -> 18_000
            height >= 1440 -> 9_000
            height >= 1080 -> 3_800
            height >= 720 -> 2_000
            height >= 480 -> 900
            height >= 360 -> 500
            height >= 240 -> 250
            else -> 120
        }

        private fun bytesOf(kbps: Int, seconds: Long): Long = kbps * 125L * seconds
    }
}
