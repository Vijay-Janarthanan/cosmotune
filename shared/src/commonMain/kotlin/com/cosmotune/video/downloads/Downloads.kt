package com.cosmotune.video.downloads

import com.cosmotune.video.model.AudioStream
import com.cosmotune.video.model.VideoItem
import com.cosmotune.video.model.VideoStream
import kotlinx.coroutines.flow.StateFlow

/** The file a download is written as (spec 5.10): MP4 or WebM for a video, M4A or Opus for audio only. */
enum class DownloadContainer { MP4, WEBM, M4A, OPUS }

/** The quality a download asks for (spec 5.16): Auto (the best the device plays), one rung of the ladder, or audio only. */
sealed interface DownloadQuality {
    /** The highest rung the device decodes. */
    data object Auto : DownloadQuality

    /** One rung: a height and frame rate (a video that lacks it takes the nearest lower one). */
    data class Rung(val height: Int, val fps: Int) : DownloadQuality

    /** The audio alone. */
    data object AudioOnly : DownloadQuality
}

/** "Download subtitles too?" (spec 5.16): off, or on with a language tag; language null with enabled = each video's own language (batches). */
data class SubtitlePick(val enabled: Boolean, val language: String?)

/** What the download sheet asks for (spec 5.16): a quality and the subtitle choice. */
data class DownloadRequest(val quality: DownloadQuality, val subtitles: SubtitlePick)

/**
 * The download preferences in Video settings (spec 5.11, 5.16): "Ask before each download", and the choice remembered
 * with "Remember my choice" (used at once while [askBeforeEach] is off; Settings clears it).
 */
data class DownloadPrefs(
    val askBeforeEach: Boolean = true,
    val remembered: DownloadRequest = DownloadRequest(DownloadQuality.Auto, SubtitlePick(false, null)),
)

/**
 * One radio row of the download sheet (spec 5.16): the quality, its label ("1080p60"), the codec shown in 12.5 sp, and the
 * estimated size (from the streams' sizes for one item, [isEstimate] for "about" sizes from durations and typical bitrates).
 */
data class RungOption(val quality: DownloadQuality, val label: String, val codec: String?, val estimatedBytes: Long, val isEstimate: Boolean)

/** One subtitle language of the sheet (spec 5.16): its tag ("" = each video's original language, batches), name and the "(auto-generated)" mark. */
data class SubtitleLanguage(val tag: String, val displayName: String, val autoGenerated: Boolean)

/**
 * What the download sheet offers (spec 5.16): the rung Auto means ("1080p60"), each rung the device plays, audio only,
 * the subtitle languages, and the video's original language (null for a batch).
 */
data class DownloadOptions(
    val autoMeans: String,
    val rungs: List<RungOption>,
    val audioOnly: RungOption,
    val subtitleLanguages: List<SubtitleLanguage>,
    val originalLanguage: String?,
)

/** What a download holds (spec 5.10: the filter chips Videos, Shorts, Audio). */
enum class DownloadKind { VIDEO, SHORT, AUDIO }

/** Where a batch came from (spec 5.16): a playlist, a channel's latest uploads, watch later, the feed. */
enum class BatchKind { PLAYLIST, CHANNEL_LATEST, WATCH_LATER, FEED }

/** A batch's identity and title (spec 5.10: the group's header row). */
data class DownloadBatchInfo(val id: String, val kind: BatchKind, val title: String)

/** The concrete streams of one entry (spec 5.16): the video stream (null for audio only), the audio stream, the container, the estimated size and its label. */
data class DownloadChoice(val video: VideoStream?, val audio: AudioStream, val container: DownloadContainer, val estimatedBytes: Long, val label: String)

/** Why a download is paused (spec 5.10: "Paused", or "Paused: battery low"). */
enum class PauseReason { USER, BATTERY_LOW }

/** The state of one download (spec 5.10, 5.16). */
sealed interface DownloadState {
    /** In the queue (downloads run one at a time). */
    data object Waiting : DownloadState

    /** Held by "Only on Wi-Fi" while on mobile data. */
    data object WaitingForWifi : DownloadState

    /** Paused by the user or by a low battery. */
    data class Paused(val reason: PauseReason) : DownloadState

    /** Fetching; [fraction] done, 0..1. */
    data class Running(val fraction: Float) : DownloadState

    /** Joining the video and audio files. */
    data object Joining : DownloadState

    /** Finished: the file at [path], [bytes] long. */
    data class Done(val path: String, val bytes: Long) : DownloadState

    /** Failed, with the reason ("Failed · Try again"). */
    data class Failed(val reason: String) : DownloadState
}

/**
 * One download (spec 5.10): the item, its kind, the concrete streams, what was asked, its state, its batch, the subtitle
 * files written beside it, the language it actually got and when it was added. [subtitleGot] is the display label of
 * that language as the Downloads page shows it ("English", "English (auto-generated)"), or null when it got none.
 */
data class DownloadEntry(
    val id: String,
    val item: VideoItem,
    val kind: DownloadKind,
    val choice: DownloadChoice,
    val request: DownloadRequest,
    val state: DownloadState,
    val batch: DownloadBatchInfo?,
    val subtitleFiles: List<String>,
    val subtitleGot: String?,
    val createdMs: Long,
)

/** A batch's progress (spec 5.10: "12 of 24", Pause or Resume, Cancel). */
data class BatchState(val info: DownloadBatchInfo, val total: Int, val done: Int, val paused: Boolean)

/**
 * The download engine (spec 5.10, 5.16; plan task Y-24): the entries and batches, the sheet's options, the queue's
 * actions and the storage line ("Downloads use 1.4 GB · 21 GB free"). The screens are built against [FakeDownloadController].
 */
interface DownloadController {
    /** Every download, in the order added. */
    val downloads: StateFlow<List<DownloadEntry>>

    /** Every batch. */
    val batches: StateFlow<List<BatchState>>

    /** What the sheet offers for one item (spec 5.16: sizes from the streams). */
    suspend fun options(item: VideoItem): DownloadOptions

    /** What the sheet offers for a batch (spec 5.16: "about" sizes; the app's language and each video's own). */
    suspend fun batchOptions(items: List<VideoItem>): DownloadOptions

    /** Adds one download to the queue. */
    fun enqueue(item: VideoItem, request: DownloadRequest)

    /** Adds a batch; skips items already downloaded or queued. */
    fun enqueueBatch(info: DownloadBatchInfo, items: List<VideoItem>, request: DownloadRequest)

    /** Pauses download [id]. */
    fun pause(id: String)

    /** Resumes download [id]. */
    fun resume(id: String)

    /** Pauses every download of batch [batchId]. */
    fun pauseBatch(batchId: String)

    /** Resumes batch [batchId]. */
    fun resumeBatch(batchId: String)

    /** Cancels download [id] and deletes its partial files. */
    fun cancel(id: String)

    /** Cancels batch [batchId]. */
    fun cancelBatch(batchId: String)

    /** Removes download [id] and deletes its files. */
    fun remove(id: String)

    /** Tries a failed download again. */
    fun retry(id: String)

    /** Bytes used by downloads, bytes free. */
    fun storage(): Pair<Long, Long>
}

/** Whether [videoId] has a finished download (spec 5.0: the downloaded badge; 5.16: a batch skips it). */
fun DownloadController.isDownloaded(videoId: String): Boolean = downloads.value.any { it.item.id == videoId && it.state is DownloadState.Done }
