package com.cosmotune.video.downloads

import com.cosmotune.video.model.AudioCodec
import com.cosmotune.video.model.VideoCodec
import com.cosmotune.video.segments.FakeSegmentProvider
import com.cosmotune.video.source.FakeVideoSource
import kotlinx.coroutines.runBlocking
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertTrue

/** The sidecar beside each download (spec 5.10, plan task Y-24): `<name>.cosmotune.json` with the item, chapters, segments, subtitles and quality. */
class DownloadSidecarTest {
    private val details = runBlocking { FakeVideoSource().details("fakevideo01") }
    private val segments = FakeSegmentProvider.SAMPLE

    private val sidecar = DownloadSidecar(
        item = details.item,
        chapters = details.chapters,
        segments = segments,
        subtitles = listOf(SidecarSubtitle("Building a tiny synth from scratch [fakevideo01].en.vtt", "en", "English", autoGenerated = false)),
        quality = "720p",
        container = DownloadContainer.MP4,
        videoCodec = VideoCodec.H264,
        audioCodec = AudioCodec.AAC,
        languageGot = "English",
        files = listOf("Building a tiny synth from scratch [fakevideo01].mp4"),
        downloadedAtMs = FakeVideoSource.NOW_MS,
    )

    @Test fun theSidecarRoundTrips() {
        assertTrue(details.chapters.isNotEmpty() && segments.isNotEmpty(), "the sample has chapters and segments")
        val text = DownloadSidecar.encode(sidecar)
        assertTrue("\"version\": 1" in text, text)
        assertTrue("\"sponsor\"" in text, "segments are stored by their API names")
        assertEquals(sidecar, DownloadSidecar.decode(text))
        val audioOnly = sidecar.copy(videoCodec = null, container = DownloadContainer.M4A, subtitles = emptyList(), languageGot = null, segments = emptyList())
        assertEquals(audioOnly, DownloadSidecar.decode(DownloadSidecar.encode(audioOnly)))
    }

    @Test fun itIsNamedAfterTheVideoAndReadsLeniently() {
        assertEquals("Building a tiny synth from scratch [fakevideo01].cosmotune.json", DownloadSidecar.fileName("Building a tiny synth from scratch [fakevideo01]"))
        assertNull(DownloadSidecar.decode("{"))
        // a later version's extra fields are ignored; an unknown segment category is dropped
        val later = DownloadSidecar.encode(sidecar).replaceFirst("{", "{\"somethingNew\": true,").replace("\"sponsor\"", "\"brand_new_category\"")
        val read = DownloadSidecar.decode(later)!!
        assertEquals(sidecar.segments.size - 1, read.segments.size)
        assertEquals(sidecar.item, read.item)
    }
}
