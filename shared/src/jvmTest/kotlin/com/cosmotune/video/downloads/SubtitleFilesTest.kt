package com.cosmotune.video.downloads

import com.cosmotune.video.model.SubtitleTrack
import kotlin.test.Test
import kotlin.test.assertEquals

/** The subtitle rules of plan task Y-24, step 2 (spec 5.16): which track each download takes, its file name, and the conversion to WebVTT. */
class SubtitleFilesTest {
    private val en = SubtitleTrack("https://media.cosmotune.invalid/subs/v.en.vtt", "text/vtt", "en", "English", autoGenerated = false)
    private val hi = SubtitleTrack("https://media.cosmotune.invalid/subs/v.hi.vtt", "text/vtt", "hi", "Hindi", autoGenerated = false)
    private val enAuto = SubtitleTrack("https://media.cosmotune.invalid/subs/v.en-auto.vtt", "text/vtt", "en", "English (auto-generated)", autoGenerated = true)
    private val deAuto = SubtitleTrack("https://media.cosmotune.invalid/subs/v.de-auto.vtt", "text/vtt", "de", "German", autoGenerated = true)
    private val enGb = SubtitleTrack("https://media.cosmotune.invalid/subs/v.en-GB.vtt", "text/vtt", "en-GB", "English (United Kingdom)", autoGenerated = false)
    private val all = listOf(enAuto, hi, en)

    private fun one(tag: String) = SubtitlePick(enabled = true, language = tag)
    private val batch = SubtitlePick(enabled = true, language = null)
    private val eachOriginal = SubtitlePick(enabled = true, language = "")

    @Test fun oneVideoTakesTheChosenLanguageManualFirst() {
        assertEquals(PickedSubtitle(hi, "Hindi"), SubtitleFiles.pick(one("hi"), all, appLanguage = "en"))
        assertEquals(PickedSubtitle(en, "English"), SubtitleFiles.pick(one("en"), all, appLanguage = "hi"), "the manual track before the auto-generated one")
        assertEquals(PickedSubtitle(enAuto, "English (auto-generated)"), SubtitleFiles.pick(one("en"), listOf(enAuto, hi), appLanguage = "en"))
        assertEquals(PickedSubtitle(enGb, "English (United Kingdom)"), SubtitleFiles.pick(one("en"), listOf(enGb, deAuto), appLanguage = "en"), "a regional track matches its language")
    }

    @Test fun oneVideoFallsBackToItsOriginalLanguageThenNone() {
        // French is missing: the original language (the auto-generated track's) is English, and the manual English track wins
        val (track, label) = SubtitleFiles.pick(one("fr"), all, appLanguage = "en")
        assertEquals(en, track)
        assertEquals("English", label)
        assertEquals(PickedSubtitle(deAuto, "German (auto-generated)"), SubtitleFiles.pick(one("fr"), listOf(deAuto), appLanguage = "en"))
        assertEquals(PickedSubtitle(hi, "Hindi"), SubtitleFiles.pick(one("fr"), listOf(hi, en), appLanguage = "en", originalLanguage = "hi"))
        assertEquals(PickedSubtitle(null, "none"), SubtitleFiles.pick(one("fr"), listOf(hi), appLanguage = "en"))
        assertEquals(PickedSubtitle(null, "none"), SubtitleFiles.pick(one("en"), emptyList(), appLanguage = "en"))
        assertEquals(PickedSubtitle(null, "none"), SubtitleFiles.pick(SubtitlePick(false, "en"), all, appLanguage = "en"), "switched off")
    }

    @Test fun aBatchTakesTheAppLanguageElseEachOriginal() {
        assertEquals(PickedSubtitle(hi, "Hindi"), SubtitleFiles.pick(batch, all, appLanguage = "hi"))
        assertEquals(PickedSubtitle(en, "English"), SubtitleFiles.pick(batch, all, appLanguage = "fr"))
        assertEquals(PickedSubtitle(deAuto, "German (auto-generated)"), SubtitleFiles.pick(batch, listOf(deAuto), appLanguage = "fr"))
        assertEquals(PickedSubtitle(null, "none"), SubtitleFiles.pick(batch, listOf(hi), appLanguage = "fr"))
        // "Each video's original language" goes straight to the original
        assertEquals(PickedSubtitle(en, "English"), SubtitleFiles.pick(eachOriginal, all, appLanguage = "hi"))
        assertEquals(PickedSubtitle(null, "none"), SubtitleFiles.pick(eachOriginal, listOf(hi), appLanguage = "hi"))
    }

    @Test fun theFileSitsBesideTheVideoWithItsLanguage() {
        assertEquals("Building a tiny synth [fakevideo01].en.vtt", SubtitleFiles.fileName("Building a tiny synth [fakevideo01]", "en"))
        assertEquals("x [id].pt-BR.vtt", SubtitleFiles.fileName("x [id]", "pt-BR"))
    }

    @Test fun ttmlBecomesWebVtt() {
        val ttml = """
            <?xml version="1.0" encoding="utf-8" ?>
            <tt xml:lang="en" xmlns="http://www.w3.org/ns/ttml"><head/><body><div>
            <p begin="00:00:01.000" end="00:00:03.500" style="s2">Hello &amp; welcome<br />to the show</p>
            <p begin="00:00:04.250" dur="2s">Tom &lt;3 <span tts:color="red">Jerry</span></p>
            <p begin="61.5s" end="62.75s">It&apos;s &#233;t&#xE9;</p>
            <p begin="00:00:09.000" end="00:00:10.000"></p>
            </div></body></tt>
        """.trimIndent()
        assertEquals(
            "WEBVTT\n\n" +
                "00:00:01.000 --> 00:00:03.500\nHello &amp; welcome\nto the show\n\n" +
                "00:00:04.250 --> 00:00:06.250\nTom &lt;3 Jerry\n\n" +
                "00:01:01.500 --> 00:01:02.750\nIt's été\n",
            SubtitleFiles.toVtt(ttml, SubtitleFormat.TTML),
        )
    }

    @Test fun srtBecomesWebVtt() {
        val srt = "1\r\n00:00:01,000 --> 00:00:02,500\r\nHello <i>there</i>\r\n\r\n2\r\n00:01:02,003 --> 00:01:04,000\r\nFish & chips -> two\r\nlines\r\n"
        assertEquals(
            "WEBVTT\n\n00:00:01.000 --> 00:00:02.500\nHello <i>there</i>\n\n00:01:02.003 --> 00:01:04.000\nFish &amp; chips -&gt; two\nlines\n",
            SubtitleFiles.toVtt(srt, SubtitleFormat.SRT),
        )
    }

    @Test fun timedTextFormatThreeBecomesWebVtt() {
        val srv3 = """<?xml version="1.0" encoding="utf-8" ?><timedtext format="3">
            <body>
            <p t="1200" d="2300">Hi <s t="400">there</s></p>
            <p t="5000" d="1000"></p>
            <p t="3723004" d="500">It&#39;s fine</p>
            </body></timedtext>"""
        assertEquals(
            "WEBVTT\n\n00:00:01.200 --> 00:00:03.500\nHi there\n\n01:02:03.004 --> 01:02:03.504\nIt's fine\n",
            SubtitleFiles.toVtt(srv3, SubtitleFormat.SRV3),
        )
    }

    @Test fun webVttPassesThroughAndTheFormatIsSniffed() {
        val vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nSame\n"
        assertEquals(vtt, SubtitleFiles.toVtt(vtt, SubtitleFormat.VTT))
        assertEquals(vtt, SubtitleFiles.toVtt("﻿" + vtt, SubtitleFormat.UNKNOWN), "the byte-order mark goes")
        assertEquals(SubtitleFormat.TTML, SubtitleFormat.of("application/ttml+xml", null, "<tt xmlns=\"http://www.w3.org/ns/ttml\"></tt>"))
        assertEquals(SubtitleFormat.SRV3, SubtitleFormat.of("text/xml", null, "<?xml version=\"1.0\"?><timedtext format=\"3\"></timedtext>"))
        assertEquals(SubtitleFormat.SRT, SubtitleFormat.of(null, null, "1\n00:00:01,000 --> 00:00:02,000\nx\n"))
        assertEquals(SubtitleFormat.VTT, SubtitleFormat.of("text/vtt", "https://media.cosmotune.invalid/a?fmt=vtt", "WEBVTT\n"))
        // a TTML file served as text/vtt is still read as TTML: the content decides
        assertEquals(
            "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nx\n",
            SubtitleFiles.toVtt("<tt xmlns=\"http://www.w3.org/ns/ttml\"><body><p begin=\"1s\" end=\"2s\">x</p></body></tt>", SubtitleFormat.of("text/vtt", null, "<tt")),
        )
    }
}
