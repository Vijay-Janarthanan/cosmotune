package com.cosmotune.video.downloads

import com.cosmotune.video.model.AudioCodec
import com.cosmotune.video.model.Chapter
import com.cosmotune.video.model.VideoCodec
import com.cosmotune.video.player.LocalSubtitle
import com.cosmotune.video.player.MediaInput
import com.cosmotune.video.segments.FakeSegmentProvider
import com.cosmotune.video.source.FakeVideoSource
import kotlinx.coroutines.runBlocking
import java.io.File
import java.nio.file.Files
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertTrue

/** A finished download as the player gets it offline (the owner's decision): files, subtitles, chapters and segments from the sidecar. */
class LocalBundlesTest {
    private val caps = DeviceCaps(1080, 60, setOf(VideoCodec.H264, VideoCodec.VP9))
    private val details = runBlocking { FakeVideoSource().details("fakevideo01") }
    private val request = DownloadRequest(DownloadQuality.Rung(1080, 30), SubtitlePick(true, "en"))
    private val choice = DownloadPlanner.choiceFor(request, details, caps)
    private val base = "Building a tiny synth from scratch [fakevideo01]"

    private fun entry(path: String, subtitleFiles: List<String> = emptyList(), got: String? = null) = DownloadEntry(
        "download-1", details.item, DownloadKind.VIDEO, choice, request, DownloadState.Done(path, 370_000_000), null, subtitleFiles, got, 0,
    )

    private fun sidecar(files: List<String>) = DownloadSidecar.encode(DownloadSidecar(
        item = details.item,
        chapters = details.chapters.reversed(),
        segments = FakeSegmentProvider.SAMPLE,
        subtitles = listOf(
            SidecarSubtitle("$base.en.vtt", "en", "English", autoGenerated = false),
            SidecarSubtitle("$base.de.vtt", "de", "German (auto-generated)", autoGenerated = true),
        ),
        quality = "1080p", container = DownloadContainer.MP4, videoCodec = VideoCodec.H264, audioCodec = AudioCodec.AAC,
        languageGot = "English", files = files, downloadedAtMs = FakeVideoSource.NOW_MS,
    ))

    @Test fun aJoinedDownloadBringsItsSubtitlesChaptersAndSegments() {
        val e = entry("/m/Cosmotune/$base.mp4", listOf("/m/Cosmotune/$base.en.vtt"), "English")
        assertEquals("/m/Cosmotune/$base.cosmotune.json", e.sidecarPath())
        val bundle = e.toLocalBundle(sidecar(listOf("$base.mp4")))!!
        assertEquals(MediaInput.LocalFiles("/m/Cosmotune/$base.mp4", null, null), bundle.files)
        assertEquals(
            listOf(
                LocalSubtitle("/m/Cosmotune/$base.en.vtt", "en", "English", false),
                LocalSubtitle("/m/Cosmotune/$base.de.vtt", "de", "German (auto-generated)", true),
            ),
            bundle.subtitles,
        )
        assertEquals(details.chapters, bundle.chapters, "in time order")
        assertEquals(FakeSegmentProvider.SAMPLE, bundle.segments)
    }

    @Test fun aKeptPairBringsBothHalvesAndItsSidecarSitsBesideThem() {
        val e = entry("C:\\Videos\\Cosmotune\\$base.video.mp4")
        assertEquals("C:\\Videos\\Cosmotune\\$base.cosmotune.json", e.sidecarPath())
        val bundle = e.toLocalBundle(sidecar(listOf("$base.video.mp4", "$base.audio.m4a")))!!
        assertEquals(MediaInput.LocalFiles(null, "C:\\Videos\\Cosmotune\\$base.video.mp4", "C:\\Videos\\Cosmotune\\$base.audio.m4a"), bundle.files)
        assertEquals("C:\\Videos\\Cosmotune\\$base.en.vtt", bundle.subtitles.first().path)
    }

    @Test fun withoutAReadableSidecarTheFilesAndTheEntrysSubtitlesRemain() {
        val e = entry("/m/$base.mp4", listOf("/m/$base.en.vtt"), "English (auto-generated)")
        for (broken in listOf(null, "", "{not json", "{\"version\": 1}")) {
            val bundle = e.toLocalBundle(broken)!!
            assertEquals(MediaInput.LocalFiles("/m/$base.mp4", null, null), bundle.files, "for $broken")
            assertEquals(listOf(LocalSubtitle("/m/$base.en.vtt", "en", "English (auto-generated)", true)), bundle.subtitles, "for $broken")
            assertTrue(bundle.chapters.isEmpty() && bundle.segments.isEmpty())
        }
        // the sidecar of another video is not this one's
        val other = sidecar(listOf("x.mp4")).replace("\"fakevideo01\"", "\"fakevideo02\"")
        assertTrue(e.toLocalBundle(other)!!.chapters.isEmpty())
        // nothing to play until it is done
        assertNull(e.copy(state = DownloadState.Running(0.5f)).toLocalBundle(sidecar(emptyList())))
        assertNull(e.copy(state = DownloadState.Waiting).sidecarPath())
    }

    @Test fun onEachPlatformTheSidecarIsReadFromBesideTheFile() {
        val dir = Files.createTempDirectory("y24-bundle").toFile()
        try {
            val movie = File(dir, "$base.mp4").apply { writeText("movie") }
            val e = entry(movie.path)
            assertTrue(e.readLocalBundle()!!.chapters.isEmpty(), "no sidecar yet: the files alone")
            File(dir, "$base.cosmotune.json").writeText(sidecar(listOf(movie.name)))
            val bundle = e.readLocalBundle()!!
            assertEquals(listOf(Chapter("Start", 0, null), Chapter("The main part", 90_000, null), Chapter("The end", 185_000, null)), bundle.chapters)
            assertEquals(File(dir, "$base.en.vtt").path, bundle.subtitles.first().path)
        } finally {
            dir.deleteRecursively()
        }
    }
}
