package com.cosmotune.video.downloads

import com.cosmotune.video.model.SubtitleTrack
import kotlinx.coroutines.runBlocking
import okhttp3.mockwebserver.MockResponse
import okhttp3.mockwebserver.MockWebServer
import java.io.File
import java.io.IOException
import java.nio.file.Files
import kotlin.test.AfterTest
import kotlin.test.BeforeTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse

/** Fetching a subtitle track beside a download (plan task Y-24, step 2), against a local server. */
class SubtitleFetcherTest {
    private lateinit var server: MockWebServer
    private lateinit var dir: File
    private val ttml = "<tt xmlns=\"http://www.w3.org/ns/ttml\"><body><div><p begin=\"00:00:01.000\" end=\"00:00:02.000\">One<br/>two</p></div></body></tt>"

    @BeforeTest fun start() {
        server = MockWebServer()
        server.start()
        dir = Files.createTempDirectory("y24-subs").toFile()
    }

    @AfterTest fun stop() {
        server.shutdown()
        dir.deleteRecursively()
    }

    private fun track(path: String, mime: String = "application/ttml+xml") = SubtitleTrack(server.url(path).toString(), mime, "en", "English", autoGenerated = false)

    @Test fun ttmlIsWrittenAsWebVtt() = runBlocking {
        server.enqueue(MockResponse().setBody(ttml))
        val file = File(dir, "Video [id].en.vtt")
        SubtitleFetcher(retryDelayMs = 0).fetch(track("/subs/en"), file, mapOf("User-Agent" to "test"))
        assertEquals("WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nOne\ntwo\n", file.readText())
        val request = server.takeRequest()
        assertEquals("GET", request.method)
        assertEquals("test", request.getHeader("User-Agent"))
        assertFalse(File(dir, "Video [id].en.vtt.part").exists())
    }

    @Test fun itRetriesTwice() = runBlocking {
        server.enqueue(MockResponse().setResponseCode(500))
        server.enqueue(MockResponse().setResponseCode(503))
        server.enqueue(MockResponse().setBody("WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nThird time\n"))
        val file = File(dir, "v.en.vtt")
        SubtitleFetcher(retryDelayMs = 0).fetch(track("/subs/en", "text/vtt"), file)
        assertEquals(3, server.requestCount)
        assertEquals("WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nThird time\n", file.readText())
    }

    @Test fun threeFailuresGiveUp() {
        repeat(3) { server.enqueue(MockResponse().setResponseCode(500)) }
        val file = File(dir, "v.en.vtt")
        assertFailsWith<IOException> { runBlocking { SubtitleFetcher(retryDelayMs = 0).fetch(track("/subs/en"), file) } }
        assertEquals(3, server.requestCount)
        assertFalse(file.exists())
    }
}
