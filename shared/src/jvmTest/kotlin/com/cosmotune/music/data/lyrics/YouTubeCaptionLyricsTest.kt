package com.cosmotune.music.data.lyrics

import kotlinx.serialization.json.Json
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertTrue

class YouTubeCaptionLyricsTest {

    private val auto = YouTubeCaptionLyrics.Track("https://www.youtube.com/api/timedtext?v=a&lang=ta&kind=asr", "ta", true)
    private val uploadedTamil = YouTubeCaptionLyrics.Track("https://www.youtube.com/api/timedtext?v=a&lang=ta-IN", "ta-IN", false)
    private val uploadedEnglish = YouTubeCaptionLyrics.Track("https://www.youtube.com/api/timedtext?v=a&lang=en", "en", false)

    @Test
    fun `an uploaded track in the sung language wins over the auto one`() {
        assertEquals(uploadedTamil, YouTubeCaptionLyrics.pickTrack(listOf(uploadedEnglish, auto, uploadedTamil)))
    }

    @Test
    fun `a translation is not picked over the auto track`() {
        assertEquals(auto, YouTubeCaptionLyrics.pickTrack(listOf(uploadedEnglish, auto)))
    }

    @Test
    fun `no auto track means no pick`() {
        assertNull(YouTubeCaptionLyrics.pickTrack(listOf(uploadedEnglish)))
    }

    @Test
    fun `tracks are read from the player response`() {
        val player = Json.parseToJsonElement(
            """{"captions":{"playerCaptionsTracklistRenderer":{"captionTracks":[
              {"baseUrl":"https://x/timedtext?v=a","languageCode":"en","kind":"asr"},
              {"baseUrl":"https://x/timedtext?v=b","languageCode":"fr"}]}}}""",
        )
        val tracks = YouTubeCaptionLyrics.tracksOf(player)
        assertEquals(2, tracks.size)
        assertTrue(tracks[0].autoGenerated)
        assertEquals("fr", tracks[1].languageCode)
    }

    @Test
    fun `auto captions keep their word timing and drop sound labels`() {
        val json = """{"events":[
          {"tStartMs":0,"dDurationMs":2000,"segs":[{"utf8":"[Music]"}]},
          {"tStartMs":1000,"dDurationMs":4000,"segs":[{"utf8":"hello"},{"utf8":" there","tOffsetMs":400},{"utf8":" friend","tOffsetMs":900}]},
          {"tStartMs":3000,"aAppend":1,"segs":[{"utf8":"\n"}]},
          {"tStartMs":3000,"dDurationMs":2000,"segs":[{"utf8":"♪ second line ♪"}]}
        ]}"""
        val lines = YouTubeCaptionLyrics.parseTimedText(json, wordTimed = true)
        assertEquals(listOf("hello there friend", "second line"), lines.map { it.text })
        val first = lines[0]
        assertEquals(1000L, first.timeMs)
        assertEquals(listOf(1000L, 1400L, 1900L), first.words.map { it.startMs })
        // The last word stops where the next caption starts, not where its window closes.
        assertEquals(3000L, first.words.last().endMs)
        assertEquals(3000L, first.sungUntilMs)
    }

    @Test
    fun `uploaded captions are line timed and a rolling repeat is dropped`() {
        val json = """{"events":[
          {"tStartMs":500,"dDurationMs":1500,"segs":[{"utf8":"one line"}]},
          {"tStartMs":2000,"dDurationMs":1500,"segs":[{"utf8":"one line"}]},
          {"tStartMs":3500,"dDurationMs":1500,"segs":[{"utf8":"another"}]}
        ]}"""
        val lines = YouTubeCaptionLyrics.parseTimedText(json, wordTimed = false)
        assertEquals(listOf(500L, 3500L), lines.map { it.timeMs })
        assertTrue(lines.none { it.isWordSynced })
    }

    @Test
    fun `junk is not lyrics`() {
        assertTrue(YouTubeCaptionLyrics.parseTimedText("not json", wordTimed = true).isEmpty())
        assertTrue(YouTubeCaptionLyrics.parseTimedText("""{"wireMagic":"pb3"}""", wordTimed = true).isEmpty())
    }

    @Test
    fun `the caption track is the last source asked`() {
        assertEquals(LyricsSource.YOUTUBE_CAPTION_TRACK, LyricsSource.offered.last())
        val saved = LyricsSource.offered - LyricsSource.YOUTUBE_CAPTION_TRACK
        assertEquals(LyricsSource.YOUTUBE_CAPTION_TRACK, LyricsSource.ordered(saved).last())
    }
}
