/** Room under the last row, as the other sheets keep. */
private val LIST_END = 8.dp

/**
 * The subtitle languages to choose from (spec 5.16): one radio row per language of [languages] in the engine's order (a person's
 * tracks first), an automatic one marked "(auto-generated)" under its name; for a batch the app's language and "Each video's original
 * language". [selected] has the check; [onPick] takes a row. With [onBack] (the desktop dialog, where the list takes the dialog's place)
 * the first row goes back to the options; without it (the phone's own sheet) the heading names the list. [firstFocus] goes on the
 * chosen row.
 */
@Composable
internal fun ColumnScope.SubtitleLanguageListBody(
    languages: List<SubtitleLanguage>,
    selected: SubtitleLanguage?,
    onPick: (SubtitleLanguage) -> Unit,
    onBack: (() -> Unit)?,
    firstFocus: FocusRequester? = null,
) {
    val title = stringResource(Res.string.video_dl_subtitle_language)
    if (onBack != null) {
        DownloadNavRow(icon = CosmoIcons.ArrowLeft, title = title, detail = null, onClick = onBack, clickLabel = stringResource(SharedRes.string.cosmo_back), chevron = false)
    } else {
        CosmoSheetHeading(title)
    }
    val autoMark = stringResource(Res.string.video_dl_auto_generated)
    Column(Modifier.fillMaxWidth().selectableGroup()) {
        for (language in languages) {
            key(language.tag, language.autoGenerated) {
                val chosen = language == selected
                DownloadRadioRow(
                    title = subtitleLanguageName(language),
                    detail = if (language.autoGenerated) autoMark else null,
                    selected = chosen,
                    onSelect = { onPick(language) },
                    modifier = if (chosen && firstFocus != null) Modifier.focusRequester(firstFocus) else Modifier,
                )
            }
        }
    }
    Spacer(Modifier.height(LIST_END))
}

/** The phone's language list: a sheet of its own over the download sheet (part two's sheet, no backdrop blur); [onDismiss] goes back. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
internal fun SubtitleLanguageSheet(
    languages: List<SubtitleLanguage>,
    selected: SubtitleLanguage?,
    onPick: (SubtitleLanguage) -> Unit,
    onDismiss: () -> Unit,
) {
    SurfaceSheetSwitch(onDismissRequest = onDismiss, sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)) {
        SubtitleLanguageListBody(languages, selected, onPick, onBack = null)
    }
}

/** A language's name: "Each video's original language" for the batch's tag "", else the engine's name ("English"). */
@Composable
internal fun subtitleLanguageName(language: SubtitleLanguage): String =
    if (language.tag.isEmpty()) stringResource(Res.string.video_dl_each_original) else language.displayName

/** The chosen language as the sheet's language row shows it: its name, and "(auto-generated)" after an automatic one. */
@Composable
internal fun subtitleLanguageLabel(language: SubtitleLanguage): String {
    val name = subtitleLanguageName(language)
    return if (language.autoGenerated) "$name ${stringResource(Res.string.video_dl_auto_generated)}" else name
}
