/**
 * The desktop's video engine (spec 6.3, plan task Y-12): libmpv ([MpvNatives], [MpvPlayer]) rendering in software into
 * buffers Compose draws ([MpvRenderer], [Surface]), fed by the [LoopbackProxy]. One per process ([shared]).
 *
 * - **Threads.** Every method may be called from any thread and returns at once: the work goes to the engine's own thread in
 *   order (the controller holds its lock while it calls in, so nothing here blocks on it or calls back into it). The snapshot
 *   changes on mpv's events, never per frame; [positionMs] reads a clock and never calls into mpv.
 * - **Loading.** [load] does not start playback. Progressive streams (and the two streams of a DASH input: the desktop does not
 *   take the manifest, `sideloadedDash = false`) play as `Edl.join(proxy(video), proxy(audio))`; a muxed or single stream as
 *   its proxy address; HLS directly (live: from the live edge, with FFmpeg's reconnect options); downloaded files directly
 *   (a pair joined by EDL). The start is the request's `startMs`; the subtitles of the language chosen with [selectSubtitle]
 *   are added with `sub-add` once the file is loaded; a downloaded video's subtitle files (`localSubtitles`) are all added
 *   as tracks and chosen by language the same way.
 * - **Unloading.** [unload] stops the file and lets go of the frames and the proxy's streams; the engine stays usable.
 * - **Errors.** The proxy's 403, mpv's "HTTP error 403", or a remote file ending in an error: [PlayerErrorKind.SOURCE_EXPIRED]
 *   (the controller asks for fresh streams); the proxy unable to reach the source: `NETWORK`. When no libmpv loads on this
 *   computer, every command does nothing and the snapshot holds [PlayerErrorKind.UNSUPPORTED] (the watch page then says "Video
 *   playback is not available on this computer").
 * - **Background.** [setAudioOnly] sets `vid=no` (and `vid=auto` back): the same source keeps playing (spec 6.1, 6.3).
 */
class DesktopVideoEngine internal constructor(
    private val natives: () -> MpvLibrary?,
    private val upstreamClient: OkHttpClient?,
    private val playerOptions: Map<String, String>,
) : VideoPlayerEngine, VideoSurfaceProvider {

    /** The engine of a running app: libmpv from the runtime jar, the default HTTP client and the options of spec 6.3. */
    constructor() : this({ MpvNatives.load() }, null, emptyMap())

    /** One subtitle file a request offers: a side-loaded track's address or a downloaded file's path. */
    internal class SubtitleChoice(val url: String, val language: String, val label: String, val autoGenerated: Boolean)

    override val capabilities: EngineCapabilities by lazy { DesktopCapabilities.of() }

    private val snapshotFlow = MutableStateFlow(PlayerSnapshot.Idle)
    override val snapshot: StateFlow<PlayerSnapshot> = snapshotFlow.asStateFlow()

    private val cueFlow = MutableStateFlow<List<SubtitleCue>>(emptyList())
    override val cues: StateFlow<List<SubtitleCue>> = cueFlow.asStateFlow()

    private val exchange = FrameExchange()
    private val executor: ExecutorService = Executors.newSingleThreadExecutor { task ->
        Thread(task, "cosmotune-video-engine").apply { isDaemon = true }
    }

    /** The number of the latest load or unload; a task of an older one is skipped. */
    private val generation = AtomicInteger()
    @Volatile private var pendingStartMs = 0L
    @Volatile private var playerRef: MpvPlayer? = null
    @Volatile private var proxyRef: LoopbackProxy? = null
    @Volatile private var currentToken: String? = null
    @Volatile private var unsupported = false
    @Volatile private var released = false
    @Volatile private var audioOnly = false
    @Volatile private var subtitleLanguage: String? = null

    // The engine thread's own state.
    private var renderer: MpvRenderer? = null
    private var request: PlaybackRequest? = null
    private var pendingSeekMs: Long? = null
    private val addedSubtitles = HashSet<String>()

    // ---- VideoPlayerEngine --------------------------------------------------------------------------------------------

    override fun positionMs(): Long {
        val player = playerRef
        return if (player == null || player.pending()) pendingStartMs else player.positionMs()
    }

    override fun load(request: PlaybackRequest) {
        if (released) return
        val number = generation.incrementAndGet()
        pendingStartMs = if (request.live) 0 else request.startMs.coerceAtLeast(0)
        exchange.clear()
        cueFlow.value = emptyList()
        snapshotFlow.update {
            if (unsupported) unsupportedSnapshot(it)
            else PlayerSnapshot.Idle.copy(
                status = PlayerStatus.LOADING, speed = it.speed, muted = it.muted, audioOnly = it.audioOnly, bandwidthKbps = it.bandwidthKbps,
            )
        }
        post { doLoad(number, request) }
    }

    override fun play() = post { playerRef?.set("pause", "no") }

    override fun pause() = post { playerRef?.set("pause", "yes") }

    override fun seekTo(ms: Long) {
        val target = ms.coerceAtLeast(0)
        val player = playerRef
        if (player == null || player.pending()) pendingStartMs = target else player.jumpClock(target)
        post {
            val p = playerRef ?: return@post
            if (p.isLoaded()) p.seek(target) else pendingSeekMs = target
        }
    }

    override fun setSpeed(speed: Float) {
        val value = speed.coerceIn(MIN_SPEED, MAX_SPEED)
        post { playerRef?.set("speed", String.format(Locale.ROOT, "%.2f", value)) }
    }

    override fun setVolume(volume: Float) {
        val value = (volume.coerceIn(0f, 1f) * 100).toInt()
        post { playerRef?.set("volume", value.toString()) }
    }

    override fun setMuted(muted: Boolean) {
        snapshotFlow.update { it.copy(muted = muted) }
        post { playerRef?.set("mute", if (muted) "yes" else "no") }
    }

    override fun setAudioOnly(audioOnly: Boolean) {
        this.audioOnly = audioOnly
        snapshotFlow.update { it.copy(audioOnly = audioOnly) }
        post { playerRef?.set("vid", if (audioOnly) "no" else "auto") }
    }

    override fun selectSubtitle(language: String?) {
        subtitleLanguage = language
        post { applySubtitles() }
    }

    /**
     * Stops what plays and lets go of it: mpv's file (`stop`; the core stays, idle), the frame buffers, the proxy's streams
     * (a new session, the old requests cancelled), the subtitles and a pending seek. The snapshot is IDLE at once; the next
     * [load] starts again.
     */
    override fun unload() {
        if (released) return
        val number = generation.incrementAndGet()
        pendingStartMs = 0
        exchange.clear(freeBuffers = true)
        cueFlow.value = emptyList()
        snapshotFlow.update {
            if (unsupported) unsupportedSnapshot(it)
            else PlayerSnapshot.Idle.copy(speed = it.speed, muted = it.muted, audioOnly = it.audioOnly, bandwidthKbps = it.bandwidthKbps)
        }
        post {
            request = null
            pendingSeekMs = null
            addedSubtitles.clear()
            currentToken = null
            proxyRef?.reset()
            playerRef?.stop(number)
        }
    }

    override fun release() {
        if (released) return
        released = true
        generation.incrementAndGet()
        exchange.clear(freeBuffers = true)
        cueFlow.value = emptyList()
        snapshotFlow.value = PlayerSnapshot.Idle
        try {
            executor.execute {
                renderer?.close()
                renderer = null
                playerRef?.close()
                playerRef = null
                proxyRef?.close()
                proxyRef = null
            }
        } catch (_: RejectedExecutionException) {
        }
        executor.shutdown()
    }

    // ---- VideoSurfaceProvider -----------------------------------------------------------------------------------------

    /** Draws the newest frame, placed by [scale], and tells the renderer the space's pixel size (spec 6.3). */
    @Composable
    override fun Surface(modifier: Modifier, scale: VideoScale) {
        FrameCanvas(exchange, modifier, scale)
    }

    // ---- the engine thread --------------------------------------------------------------------------------------------

    private fun post(task: () -> Unit) {
        if (released) return
        try {
            executor.execute {
                try {
                    task()
                } catch (e: Exception) {
                    System.err.println("Cosmotune video engine: ${e.javaClass.simpleName}: ${e.message}")
                }
            }
        } catch (_: RejectedExecutionException) {
        }
    }

    private fun doLoad(number: Int, request: PlaybackRequest) {
        if (number != generation.get()) return // a newer load or unload came first
        val player = ensurePlayer() ?: return
        this.request = request
        pendingSeekMs = null
        addedSubtitles.clear()
        val target = target(request)
        if (target == null) {
            player.fail(number, PlayerError(PlayerErrorKind.UNSUPPORTED, "nothing this engine can play in the request"))
            return
        }
        target.error?.let {
            player.fail(number, it)
            return
        }
        val userAgent = if (target.direct) request.headers.entries.firstOrNull { it.key.equals("User-Agent", true) }?.value else null
        val fields = if (target.direct) headerFields(request.headers) else emptyList()
        player.load(number, target.url, request.startMs.coerceAtLeast(0), request.live, target.remote, audioOnly, userAgent, fields)
    }

    /** What mpv opens for [request]: the address, whether it reaches the network, whether mpv talks to the source itself. */
    private class Target(val url: String, val remote: Boolean, val direct: Boolean, val error: PlayerError? = null)

    private fun target(request: PlaybackRequest): Target? = when (val input = request.input) {
        is MediaInput.Progressive -> proxied(input.video, input.audio, request.headers)
        is MediaInput.Dash -> proxied(input.video, input.audio, request.headers)
        is MediaInput.Hls -> {
            currentToken = null
            Target(input.url, remote = true, direct = true)
        }
        is MediaInput.LocalFiles -> {
            currentToken = null
            val muxed = input.muxedPath
            val video = input.videoPath
            val audio = input.audioPath
            when {
                muxed != null -> Target(muxed, remote = false, direct = false)
                video != null && audio != null -> Target(Edl.join(video, audio), remote = false, direct = false)
                else -> (video ?: audio)?.let { Target(it, remote = false, direct = false) }
            }
        }
    }

    private fun proxied(video: VideoStream?, audio: AudioStream?, headers: Map<String, String>): Target? {
        if (video == null && audio == null) return null
        val proxy = ensureProxy()
            ?: return Target("", remote = true, direct = false, error = PlayerError(PlayerErrorKind.UNSUPPORTED, "the loopback server is not available"))
        currentToken = proxy.reset()
        val videoUrl = video?.let { proxy.register(it.url, headers, it.contentLength) }
        // A muxed stream carries its own sound: its audio is not added again.
        val audioUrl = audio?.takeIf { video?.hasAudio != true }?.let { proxy.register(it.url, headers, it.contentLength) }
        val url = if (videoUrl != null && audioUrl != null) Edl.join(videoUrl, audioUrl) else (videoUrl ?: audioUrl)!!
        return Target(url, remote = true, direct = false)
    }

    private fun ensureProxy(): LoopbackProxy? {
        proxyRef?.let { return it }
        return try {
            LoopbackProxy(
                onExpired = ::onExpired,
                client = upstreamClient ?: LoopbackProxy.defaultClient(),
                onBandwidth = ::onBandwidth,
            ).also { proxyRef = it }
        } catch (e: Throwable) {
            // LinkageError when the runtime lacks the module jdk.httpserver, IOException when no loopback port is free.
            System.err.println("Cosmotune video: the loopback server cannot start: ${e.javaClass.simpleName}: ${e.message}")
            null
        }
    }

    private fun ensurePlayer(): MpvPlayer? {
        playerRef?.let { return it }
        if (!unsupported) {
            val mpv = natives()
            if (mpv != null) {
                try {
                    val player = MpvPlayer(
                        mpv = mpv,
                        snapshot = snapshotFlow,
                        cues = cueFlow,
                        options = MpvPlayer.DEFAULT_OPTIONS + playerOptions,
                        latestLoad = generation::get,
                        onVideoSize = exchange::setVideoSize,
                        onFileLoaded = { post(::afterFileLoaded) },
                        networkTrouble = { proxyRef?.networkFailed == true },
                    )
                    val renderer = MpvRenderer(mpv, player.handle, exchange)
                    if (renderer.start()) {
                        this.renderer = renderer
                        playerRef = player
                        return player
                    }
                    renderer.close()
                    player.close()
                } catch (e: Throwable) {
                    System.err.println("Cosmotune video: mpv could not start: ${e.javaClass.simpleName}: ${e.message}")
                }
            }
            unsupported = true
        }
        snapshotFlow.update { unsupportedSnapshot(it) }
        return null
    }

    private fun unsupportedSnapshot(from: PlayerSnapshot): PlayerSnapshot = PlayerSnapshot.Idle.copy(
        status = PlayerStatus.ERROR, muted = from.muted, audioOnly = from.audioOnly,
        error = PlayerError(PlayerErrorKind.UNSUPPORTED, "video playback is not available on this computer"),
    )

    /** The file is loaded: a seek asked for while it loaded, then the subtitles. */
    private fun afterFileLoaded() {
        val player = playerRef ?: return
        if (!player.isLoaded()) return
        pendingSeekMs?.let {
            pendingSeekMs = null
            player.seek(it)
        }
        applySubtitles()
    }

    private fun applySubtitles() {
        val player = playerRef ?: return
        val current = request ?: return
        if (!player.isLoaded()) return // afterFileLoaded comes back
        val choices = subtitleChoices(current)
        // Offline: every downloaded subtitle file is a track of the video (`sub-add <path> auto`), as the source offers them.
        for (local in current.localSubtitles) if (addedSubtitles.add(local.path)) player.addSubtitles(local.path, local.label, local.language)
        val chosen = pickSubtitle(choices, subtitleLanguage)
        if (chosen == null) {
            player.showSubtitles(null, alreadyAdded = false)
        } else {
            player.showSubtitles(chosen.url, alreadyAdded = chosen.url in addedSubtitles)
            addedSubtitles += chosen.url
        }
    }

    private fun onExpired(token: String) {
        if (token == currentToken) playerRef?.markExpired("the source answered 403")
    }

    private fun onBandwidth(kbps: Int) {
        snapshotFlow.update {
            val old = it.bandwidthKbps
            if (old == null || abs(kbps - old) * 10 >= old) it.copy(bandwidthKbps = kbps) else it
        }
    }

    companion object {
        /** The engine of the running app, made on first use. */
        val shared: DesktopVideoEngine by lazy { DesktopVideoEngine() }

        private const val MIN_SPEED = 0.25f
        private const val MAX_SPEED = 4f

        /**
         * The subtitle files [request] offers: its side-loaded tracks (addresses mpv fetches when one is chosen) and a
         * downloaded video's own files (`localSubtitles`, paths on this computer), found the same way by language.
         */
        internal fun subtitleChoices(request: PlaybackRequest): List<SubtitleChoice> =
            request.subtitles.map { SubtitleChoice(it.url, it.language, it.name, it.autoGenerated) } +
                request.localSubtitles.map { SubtitleChoice(it.path, it.language, it.label, it.autoGenerated) }

        /**
         * The file for [language]: an exact language match before one of the same base language ("en" for "en-GB"), a
         * person's subtitles before automatic ones; null for no language or none of it.
         */
        internal fun pickSubtitle(choices: List<SubtitleChoice>, language: String?): SubtitleChoice? {
            if (language.isNullOrBlank()) return null
            val exact = choices.filter { it.language.equals(language, ignoreCase = true) }
            val base = language.substringBefore('-').lowercase()
            val near = exact.ifEmpty { choices.filter { it.language.substringBefore('-').lowercase() == base } }
            // A person's track first, then the plain base language ("en" before "en-GB" for "en-US"); the list's order otherwise.
            return near.minWithOrNull(compareBy<SubtitleChoice>({ it.autoGenerated }, { !it.language.equals(base, ignoreCase = true) }))
        }

        /** The headers mpv sends itself to an HLS source, as `Name: value` (the User-Agent goes separately; a value with a comma cannot be listed). */
        internal fun headerFields(headers: Map<String, String>): List<String> =
            headers.filter { !it.key.equals("User-Agent", ignoreCase = true) && ',' !in it.value && ',' !in it.key }
                .map { "${it.key}: ${it.value}" }
    }
}
