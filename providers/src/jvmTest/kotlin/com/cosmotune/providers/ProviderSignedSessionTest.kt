class ProviderSignedSessionTest {
    @get:Rule val temporary = TemporaryFolder()
    private val fixedNow = 1_792_800_000_123L
    private inner class Fixture(refresh: Boolean = false) : AutoCloseable {
        val server = MockWebServer()
        var clock = fixedNow
        val certificate = HeldCertificate.Builder().addSubjectAlternativeName("localhost").build()
        init { server.useHttps(HandshakeCertificates.Builder().heldCertificate(certificate).build().sslSocketFactory(), false); server.start() }
        val config = buildJsonObject {
            put("namespace", "fixture"); put("baseUrl", server.url("/v2").toString())
            put("schemeLabel", "TEST-HMAC-V1"); put("headerPrefix", "X-Test-"); put("appVersion", "fixture@1")
            put("callbackUrl", "cosmotune://provider-auth/session-grant")
            if (refresh) putJsonObject("endpoints") { put("refresh", "/session/refresh") }
        }
        val install = ProviderInstall(ProviderManifest("fixture", "1.0.0", type = listOf("metadata_provider"),
            permissions = ProviderPermissions(listOf("localhost"), storage = true), signedSession = config), "0".repeat(64), allowLocalNetwork = true)
        val store = ProviderStore(temporary.newFolder(), UnsealedProviderFiles)
        val trust = HandshakeCertificates.Builder().addTrustedCertificate(certificate.certificate).build()
        val network = ProviderNetwork(install.manifest.permissions, true, OkHttpClient.Builder().sslSocketFactory(trust.sslSocketFactory(), trust.trustManager).build())
        init { runBlocking { store.update { it.copy(installed = listOf(install)) } } }
        val session = ProviderSignedSession(install, store, network) { clock }
        fun record(id: String = "session-fixture", secret: String = "secret-fixture", lifetime: Long = 7_200_000) = buildJsonObject {
            put("session_id", id); put("session_secret", secret); put("expires_at", Instant.ofEpochMilli(clock + lifetime).toString())
        }
        fun enqueue(body: JsonObject = record(), status: Int = 200) { server.enqueue(MockResponse().setResponseCode(status).setBody(body.toString())) }
        fun fetch(method: String = "GET", path: String = "/songs", body: String = "", headers: JsonObject = JsonObject(emptyMap())) =
            session.call("signedFetch", buildJsonArray { add(method); add(path); add(body); add(headers) }).jsonObject
        fun received() = requireNotNull(server.takeRequest(3, TimeUnit.SECONDS))
        override fun close() { network.cancel(); server.close() }
    }

    @Test fun signaturesMatchThePinnedIndependentNodeProtocolVector() {
        // Fixture generated by the pinned upstream signedHeaders function, not this implementation.
        val headers = ProviderSignedSession.headers("TEST-HMAC-V1", "X-Test-", 300, "fixture@1", "extension",
            "session-fixture", "secret-fixture", "POST", "https://example.com/v2/a%20b?ignored=yes".toHttpUrl(),
            """{"hello":"world"}""", fixedNow, "0123456789abcdef0123456789abcdef")
        assertEquals("2026-10-24T00:00:00.123Z", headers["X-Test-Timestamp"])
        assertEquals("93a23971a914e5eacbf0a8d25154cda309c3c1c72fbb9914d47c60f3cb681588", headers["X-Test-Body-SHA256"])
        assertEquals("uKWKnHEIr-jd-aRrbvlk-sLZ_0Q-4NvnjjqORPgmeqs", headers["X-Test-Signature"])
    }

    @Test fun bootstrapAndSignedRequestsUseRealTlsAndCannotOverrideTheSignature() {
        Fixture().use { f ->
            f.enqueue(); f.enqueue(buildJsonObject { put("songs", true) })
            val response = f.fetch("POST", "/songs", """{"hello":"world"}""", buildJsonObject { put("x-test-signature", "forged"); put("X-Trace", "trace") })
            assertEquals(JsonPrimitive(true), response["ok"])
            val bootstrap = f.received(); val sent = f.received()
            assertEquals("/v2/bootstrap", bootstrap.requestUrl!!.encodedPath)
            assertEquals("fixture@1", bootstrap.requestUrl!!.queryParameter("app_version"))
            assertTrue(bootstrap.requestUrl!!.queryParameter("install_id")!!.matches(Regex("[0-9a-f]{32}")))
            assertNull(bootstrap.getHeader("X-Test-Signature"))
            assertEquals("/v2/songs", sent.path); assertEquals("trace", sent.getHeader("X-Trace"))
            assertEquals("session-fixture", sent.getHeader("X-Test-Session"))
            assertNotEquals("forged", sent.getHeader("X-Test-Signature"))
            assertTrue(sent.getHeader("X-Test-Nonce")!!.matches(Regex("[0-9a-f]{32}")))
            assertEquals("93a23971a914e5eacbf0a8d25154cda309c3c1c72fbb9914d47c60f3cb681588", sent.getHeader("X-Test-Body-SHA256"))
            assertEquals(JsonPrimitive(true), f.session.call("status", JsonArray(emptyList())).jsonObject["authenticated"])
            assertFalse(f.session.call("status", JsonArray(emptyList())).toString().contains("secret-fixture"))
        }
    }

    private fun challenge(f: Fixture): Pair<String, String> {
        f.enqueue(buildJsonObject { put("challenge_id", "operator-challenge") })
        val response = f.fetch()
        assertEquals(JsonPrimitive(true), response["needsVerification"])
        val url = response.getValue("open_auth_url").jsonPrimitive.content.toHttpUrl()
        val nested = java.net.URI(url.queryParameter("cb"))
        val state = nested.rawQuery.substringAfter("state=")
        f.received()
        return "cosmotune://provider-auth/session-grant?grant=fixture-grant&state=$state" to state
    }

    @Test fun operatorChallengeRequiresItsExactUnexpiredOneUseProofBeforeGrantExchange() {
        Fixture().use { f ->
            val (callback, state) = challenge(f)
            val before = f.store.state.value.auth
            listOf(callback.replace("state=", "state=wrong"), callback.replace("/session-grant?", "/wrong?"),
                "$callback&state=$state", "$callback&code=ambiguous").forEach {
                assertFailsWith<IllegalArgumentException> { f.session.completeCallback(it) }
            }
            assertEquals(before, f.store.state.value.auth)
            f.session.completeCallback(callback)
            assertFailsWith<IllegalArgumentException> { f.session.completeCallback(callback) }
            assertEquals(JsonPrimitive(true), f.fetch()["needsVerification"], "Received grants must not be overwritten by another challenge")
            assertEquals(1, f.server.requestCount)
            f.enqueue()
            assertEquals(JsonPrimitive(true), f.session.call("completeGrant", JsonArray(emptyList())).jsonObject["success"])
            val exchange = f.received(); assertEquals("/v2/session/exchange", exchange.path)
            assertEquals("fixture-grant", Json.parseToJsonElement(exchange.body.readUtf8()).jsonObject["grant"]?.jsonPrimitive?.content)
            assertNull(f.store.state.value.auth["fixture"]?.get("grant")); assertNull(f.store.state.value.auth["fixture"]?.get("pending"))
            assertFailsWith<IllegalArgumentException> { f.session.completeCallback(callback) }
            val reopened = ProviderSignedSession(f.install, f.store, f.network) { f.clock }
            assertEquals(JsonPrimitive(true), reopened.call("status", JsonArray(emptyList())).jsonObject["authenticated"])
        }
    }

    @Test fun expiryAndDisconnectInvalidateChallengesAndLateOperatorResponses() = runBlocking<Unit> {
        Fixture().use { f ->
            val (callback, _) = challenge(f)
            f.clock += 180_001
            assertFailsWith<IllegalArgumentException> { f.session.completeCallback(callback) }
            f.session.call("clear", JsonArray(emptyList()))
            assertNull(f.store.state.value.auth["fixture"]?.get("pending"))
        }
        Fixture().use { f ->
            f.session.call("status", JsonArray(emptyList()))
            val original = f.store.state.value.auth["fixture"]
            // Bootstrap is slow enough to let native Disconnect supersede its protected epoch.
            f.server.enqueue(MockResponse().setBody(f.record().toString()).setBodyDelay(400, TimeUnit.MILLISECONDS))
            supervisorScope {
                val pending = async(Dispatchers.IO) { f.fetch() }
                withContext(Dispatchers.IO) { f.received() }
                ProviderManager(f.store).use { it.clearAuthentication("fixture") }
                assertFailsWith<IllegalStateException> { pending.await() }
            }
            assertNotEquals(original, f.store.state.value.auth["fixture"])
            assertNull(f.store.state.value.auth["fixture"]?.get("signedSession"))
        }
    }

    @Test fun gatewayResetGetsOneFreshSessionAndProviderErrorsDoNotSilentlyReconnect() {
        Fixture().use { f ->
            f.enqueue()
            f.enqueue(buildJsonObject { put("origin", "gateway"); put("code", "SESSION_INVALID"); put("action", "bootstrap_session") }, 401)
            f.enqueue(f.record("session-new", "secret-new")); f.enqueue(buildJsonObject { put("ok", true) })
            assertEquals(JsonPrimitive(true), f.fetch()["ok"])
            val requests = (1..4).map { f.received() }
            assertEquals("session-fixture", requests[1].getHeader("X-Test-Session"))
            assertEquals("session-new", requests[3].getHeader("X-Test-Session"))
            assertNotEquals(requests[1].getHeader("X-Test-Nonce"), requests[3].getHeader("X-Test-Nonce"))
            f.enqueue(buildJsonObject { put("origin", "provider"); put("code", "SESSION_INVALID"); put("action", "bootstrap_session") }, 401)
            assertEquals(JsonPrimitive(401), f.fetch()["status"])
            f.received(); assertEquals(5, f.server.requestCount)
        }
    }

    @Test fun nearExpiryRefreshChangesTheSigningSessionAndRejectsEscapedEndpointsAndRedirects() {
        Fixture(refresh = true).use { f ->
            f.enqueue(f.record(lifetime = 1_800_000)); f.enqueue(f.record("refreshed", "new-secret")); f.enqueue(buildJsonObject { put("songs", true) })
            f.fetch()
